#pragma once

#ifndef _ORDER_EXECUTE_CONTROL_DAO_
#define _ORDER_EXECUTE_CONTROL_DAO_

#include <list>
#include <string>
#include <tuple>
#include <utility>

#include "BaseDAO.h"
#include "domain/do/chargedetails/ChargeItemDO.h"
#include "domain/do/medicationcollection/MedicationDispenseDO.h"
#include "domain/do/medicationcollection/SupplyRequestDO.h"
#include "domain/do/medicalorderexecution/ProcedureDO.h"
#include "domain/do/medicalorderexecution/OriginalOrderRequestDO.h"

struct MedicationSummaryLineRow
{
	std::string dispenseId;
	std::string patientId;
	std::string medicationId;
	std::string locationId;
	std::string unitCode;
	double quantity = 0;
	double price = 0;
};

class OrderExecuteControlDAO : public BaseDAO
{
public:
	// 批量查询医嘱执行管控业务需要的原医嘱关键数据
	std::list<std::pair<std::string, PtrOriginalOrderRequestDO>> queryOriginalOrderRequestById(
		const std::list<std::string>& orderIds,
		const string& adviceType);

	// 批量判断计划点是否已被有效终态执行记录占用
	bool existsActiveTerminalProcedureBySlot(
		const std::list<std::tuple<std::string, std::string, std::string>>& slots);

	// 根据执行记录ID批量查询有效的已执行记录
	std::list<PtrClnProcedureDO> queryCompletedProcedureById(const std::list<std::string>& procedureIds);

	// 检查是否存在已经指向待取消的已执行记录的cancel行
	bool existsCancelProcedureByRefundIds(const std::list<std::string>& refundIds);

	// Insert CANCEL procedure rows without starting or committing a transaction.
	int insertCancelProceduresNoTransaction(const std::list<ClnProcedureDO>& procedures);

	// 根据id将所有已执行记录的occurrence_slot_active计划点占用槽全部置空
	int releaseCompletedProcedureSlotsNoTransaction(const std::list<std::string>& procedureIds);

	// Check charge rows that cannot be rolled back by cancel execution.
	bool existsBlockingChargeItemsForCancellation(
		const std::list<std::string>& procedureIds,
		const std::list<std::string>& serviceRequestIds);

	// Soft-delete pending-settlement charge rows generated by order execution.
	int voidPendingChargeItemsForCancellationNoTransaction(
		const std::list<std::string>& procedureIds,
		const std::list<std::string>& serviceRequestIds,
		const std::string& operatorId);

	// Check medication dispense rows in unstable pharmacy states.
	bool existsBlockingMedicationDispensesForCancellation(const std::list<std::string>& procedureIds);

	// Query completed medication dispense rows that need pending-refund rows.
	std::list<PtrMedicationDispenseDO> queryCompletedMedicationDispensesForRefund(
		const std::list<std::string>& procedureIds);

	// Insert pending-refund medication dispense rows.
	int insertMedicationRefundDispensesNoTransaction(const std::list<MedicationDispenseDO>& dispenses);

	// Soft-delete medication dispense rows that can be directly removed.
	int softDeleteMedicationDispensesForCancellationNoTransaction(
		const std::list<std::string>& procedureIds,
		const std::string& operatorId);

	// Query summary numbers affected by canceled medication dispense rows.
	std::list<std::string> listMedicationSummaryNosByProcedureIds(const std::list<std::string>& procedureIds);

	// Check summary orders that cannot be revoked and rebuilt.
	bool existsBlockingMedicationSummaryByNos(const std::list<std::string>& summaryNos);

	// Query remaining medication summary lines after canceled rows are removed.
	std::list<MedicationSummaryLineRow> queryMedicationSummaryLinesForRebuild(const std::string& summaryNo);

	// Reassign remaining dispense rows from an old summary number to a rebuilt one.
	int reassignMedicationSummaryNoTransaction(
		const std::string& oldSummaryNo,
		const std::string& newSummaryNo,
		const std::string& operatorId);

	// Soft-delete supply-request rows for old medication summaries.
	int softDeleteMedicationSummarySupplyRequestsNoTransaction(
		const std::list<std::string>& summaryNos,
		const std::string& operatorId);

	// Remove canceled active dispense rows from old medication summaries.
	int clearMedicationSummaryNoForCancellationNoTransaction(
		const std::list<std::string>& procedureIds,
		const std::string& operatorId);

	// Insert supply-request rows for rebuilt medication summaries.
	int insertMedicationSummarySupplyRequestsNoTransaction(const std::list<SupplyRequestDO>& supplyRequests);

	// Check material dispense rows in unstable pharmacy or inventory states.
	bool existsBlockingDeviceDispensesForCancellation(const std::list<std::string>& procedureIds);

	// Restore inventory quantities for completed material dispense rows.
	int restoreInventoryForCompletedDeviceDispensesNoTransaction(
		const std::list<std::string>& procedureIds,
		const std::string& operatorId);

	// Soft-delete material dispense rows after inventory rollback.
	int softDeleteDeviceDispensesForCancellationNoTransaction(
		const std::list<std::string>& procedureIds,
		const std::string& operatorId);

	// Query derived service requests generated by canceled execution records.
	std::list<std::string> listDerivedServiceRequestIdsForCancellation(const std::list<std::string>& procedureIds);

	// Query active completed procedure rows of derived service requests.
	std::list<PtrClnProcedureDO> queryCompletedProceduresByServiceRequestIds(
		const std::list<std::string>& serviceRequestIds);

	// Soft-delete derived service request master rows.
	int softDeleteDerivedServiceRequestsNoTransaction(
		const std::list<std::string>& serviceRequestIds,
		const std::string& operatorId);

	// Soft-delete derived service request detail rows.
	int softDeleteDerivedServiceRequestDetailsNoTransaction(
		const std::list<std::string>& serviceRequestIds,
		const std::string& operatorId);

	/*根据用户 ID 查询该用户能操作的所有住院记录(encounter_id)，用于权限校验*/
	std::list<std::string> listOperableEncounterIdsByUserId(const std::string& userId);
};

#endif // !_ORDER_EXECUTE_CONTROL_DAO_
